-- Esquema de referencia. Ejecutar dentro de una base PostgreSQL llamada pedidos.
-- La ejecución normal del proyecto crea las tablas mediante Hibernate.
CREATE TABLE IF NOT EXISTS productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    categoria VARCHAR(60) NOT NULL,
    precio NUMERIC(12,2) NOT NULL CHECK (precio > 0),
    stock INTEGER NOT NULL CHECK (stock >= 0 AND stock <= 1000000),
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc VARCHAR(11) NOT NULL UNIQUE,
    razon_social VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    direccion VARCHAR(200) NOT NULL
);
CREATE TABLE IF NOT EXISTS pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    fecha TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('BORRADOR','CONFIRMADO','CANCELADO')),
    total NUMERIC(18,2) NOT NULL CHECK (total >= 0),
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS detalle_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    cantidad INTEGER NOT NULL CHECK (cantidad BETWEEN 1 AND 10000),
    precio_unitario NUMERIC(12,2) NOT NULL CHECK (precio_unitario > 0),
    UNIQUE (pedido_id, producto_id)
);
CREATE INDEX IF NOT EXISTS idx_pedidos_cliente_estado ON pedidos(cliente_id, estado);
